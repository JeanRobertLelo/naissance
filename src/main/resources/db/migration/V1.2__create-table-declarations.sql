

-- Création de la table declarations
create table declarations (
      id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      father_id int,
      mother_id int,
      child_id int,
      creation timestamp DEFAULT CURRENT_TIMESTAMP,
     -- Clé étrangère identifiant du père, de la mère et de l'enfant
     -- dans la table profiles
      constraint fk_declarations_father_id foreign key(father_id) references profiles(id),
      constraint fk_declarations_mother_id foreign key(mother_id) references profiles(id),
      constraint fk_declarations_chil_id foreign key(child_id) references profiles(id),
      constraint fk_unique_father_mother_child unique (father_id,mother_id,child_id)
);